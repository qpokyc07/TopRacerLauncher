    public LegalWindow(DocKind kind)
    {
        InitializeComponent();
        ShowDocument(kind);
    }

    private void ShowDocument(DocKind kind)
    {
        bool privacy = kind == DocKind.Privacy;

        HeaderText.Text = privacy ? "Политика конфиденциальности" : "Пользовательское соглашение";
        BodyText.Text = privacy ? PrivacyText : TermsText;

        var accent = (System.Windows.Media.Brush?)FindResource("AccentBrush");
        PrivacyTab.BorderBrush = privacy ? accent : System.Windows.Media.Brushes.Transparent;
        TermsTab.BorderBrush = privacy ? System.Windows.Media.Brushes.Transparent : accent;
    }

    private void Privacy_Click(object sender, RoutedEventArgs e) => ShowDocument(DocKind.Privacy);

    private void Terms_Click(object sender, RoutedEventArgs e) => ShowDocument(DocKind.Terms);

    private void Close_Click(object sender, RoutedEventArgs e) => Close();
